/** Учебная информационная карточка: банан в словаре соответствий. */
type FoodCard = {
  название: string;
  научное_название: string;
  съедобная_часть: string;
  вещества: Record<string, string>;
  примечание: string;
  граница_вывода: string;
};

const banana: FoodCard = {
  название: "Банан",
  научное_название: "Musa spp.",
  съедобная_часть: "мякоть спелого плода",
  вещества: {
    углеводы: "крахмал и сахара; их соотношение меняется при созревании",
    клетчатка: "пищевые волокна, часть обычного рациона",
    калий: "минерал, необходимый для работы мышц и нервной системы",
    "витамин B6": "витамин, участвующий в обмене веществ",
    "витамин C": "витамин, необходимый для синтеза коллагена",
  },
  примечание: "Состав зависит от сорта, спелости и размера плода; кожуру обычно не едят.",
  граница_вывода: "Наличие веществ не доказывает лечебный эффект порции банана.",
};

console.log(`${banana.название} (${banana.научное_название})`);
console.log(`Съедобная часть: ${banana.съедобная_часть}`);
for (const [вещество, описание] of Object.entries(banana.вещества)) {
  console.log(`${banana.название} → ${вещество}: ${описание}`);
}
console.log(`Примечание: ${banana.примечание}`);
console.log(`Граница вывода: ${banana.граница_вывода}`);
